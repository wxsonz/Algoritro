// Writes spec/grasp-craft.md: every card's Grasp and Craft with their reasons, from the card data
// (js/cards/stats.js and each card's knows, fns, uses and from). With --check it only compares,
// and exits 1 when the file is out of date (tests/cards.test.mjs runs it).
//   node tools/grasp-craft.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { ALGOS, TECHS, META, techById, bareCards, findCard, label } from '../js/cards/index.js';
import { BUILDS } from '../js/cards/decks.js';
import { CONCEPTS, SHARED, KIT, KIT_FNS, FIRE, tally } from '../js/cards/stats.js';
import { buildTotals } from '../js/core/meta-run.js';

const FILE = new URL('../spec/grasp-craft.md', import.meta.url);
const words = ks => ks.length ? ks.map(k => `${CONCEPTS[k].name} (${CONCEPTS[k].w})`).join(', ') : 'none';
const codeOf = c => [c.fns ? `${c.fns} own` : '', ...(c.uses || []).map(s => `${SHARED[s].name.split(':')[0]} (${SHARED[s].fns})`)].filter(Boolean).join(' + ') || '0';
const cell = s => String(s).replace(/\|/g, '\\|');
const brought = a => bareCards(a).filter(c => c !== a && !c.always).map(c => label(c.id));

const out = [];
const P = (...l) => out.push(...l);
P('# Grasp and Craft, card by card',
  '',
  'Generated by `node tools/grasp-craft.mjs` from the card data (`js/cards/stats.js`, and each',
  'card\'s `knows`, `fns`, `uses` and `from`); do not edit by hand. [03-stats.md §3.2](03-stats.md#32-scored-stats)',
  'defines the two scores. In short:',
  '',
  '- **Grasp** is the prior knowledge a card needs: the sum of the weights of the concepts you must',
  '  know before it makes sense. The two stacks, the 11 moves, loops and arrays are free.',
  '- **Craft** is the code it takes under the Norm, in functions (at most 25 lines and 4 parameters',
  '  each, 5 to a file). It is **counted** from real C where a study build or a reference build has',
  '  the card (`push_swap/study/`, `study/explorer-refs/`), and **estimated** where none does; each',
  '  row says which, and where from.',
  '- Both add up as **sets**. A concept learnt once, or code written once, counts once in a hand',
  `  or a build. A build adds the **base kit** (${KIT_FNS} functions) and the tiny seat (Hardcoded Three`,
  `  and the Oracle). It burns past Grasp ${FIRE.grasp} or Craft ${FIRE.craft}.`,
  '',
  '## Concepts',
  '',
  '| concept | weight |',
  '| --- | --- |',
  ...Object.values(CONCEPTS).sort((a, b) => a.w - b.w).map(c => `| ${c.name} | ${c.w} |`),
  '',
  'Weight 1 is one idea you can explain in a sentence; 2 needs a diagram or a page; 3 is a topic',
  'of its own, usually met in a course before push_swap.',
  '',
  '## Shared code',
  '',
  'Code that more than one card uses, counted once in a hand or a build.',
  '',
  '| code | functions | source |',
  '| --- | --- | --- |',
  ...Object.values(SHARED).map(s => `| ${cell(s.name)} | ${s.fns} | ${cell(s.from)} |`),
  `| **base kit**: parsing and errors, ranks, the two stacks, the 11 moves and their output, freeing, the flags and main, the disorder count | ${KIT_FNS} | ${cell(KIT.from)} |`,
  '',
  '## Algorithm cards',
  '',
  'Grasp and Craft of the bare card: with its natives, defaults and default Finisher, and the cards',
  'always in play (Rank Compression), without the base kit.',
  '',
  '| card | its own concepts | brings along | Grasp | its own code | source | Craft |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...ALGOS.map(a => `| ${a.name} | ${words(a.knows)} | ${brought(a).join(', ') || '—'} | **${a.grasp}** | ${codeOf(a)} | ${cell(a.from)} | **${a.craft}** |`),
  '',
  '## Technique cards',
  '',
  'What the card asks on its own. In a hand it adds only what the hand does not have yet.',
  '',
  '| card | role | concepts | Grasp | code | source | Craft |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...TECHS.map(t => `| ${t.name} | ${t.role}${t.always ? ' (always)' : ''} | ${words(t.knows)} | ${t.grasp} | ${codeOf(t)}${t.brings ? ` + ${t.brings.map(label).join(', ')}` : ''} | ${cell(t.from)} | ${t.craft} |`),
  ...META.map(m => `| ${m.name} | meta | ${words(m.knows)} | ${m.grasp} | ${codeOf(m)} | ${cell(m.from)} | ${m.craft} |`),
  '',
  '## Named builds',
  '',
  'The whole push_swap: three seats, the tiny seat and the base kit.',
  '',
  '| build | Grasp | Craft | concepts |',
  '| --- | --- | --- | --- |',
  ...BUILDS.map(b => { const T = buildTotals(b); return `| ${b.name} | ${T.grasp}${T.grasp > FIRE.grasp ? ' 🔥' : ''} | ${T.craft}${T.craft > FIRE.craft ? ' 🔥' : ''} | ${words(T.concepts)} |`; }),
  '');
const text = out.join('\n');
if (process.argv.includes('--check')) {
  let now = ''; try { now = readFileSync(FILE, 'utf8'); } catch {}
  if (now !== text) { console.error('spec/grasp-craft.md is out of date: run node tools/grasp-craft.mjs'); process.exit(1); }
  console.log('spec/grasp-craft.md is up to date');
} else { writeFileSync(FILE, text); console.log(`wrote spec/grasp-craft.md (${ALGOS.length} algorithm cards, ${TECHS.length + META.length} technique and meta cards)`); }
