// Ops per input for a named hand on the standard inputs of size n (cached, so pairs share inputs).
function M(name, fn, n, runs = RUNS[n]) {
  const k = `${name}@${n}#${runs}`;
  if (!memo.has(k)) memo.set(k, ops(fn, inputs(n, runs, 1)));
  return memo.get(k);
}
